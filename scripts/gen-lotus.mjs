#!/usr/bin/env node
/**
 * The NOSHASHI lotus, drawn as a vector so it is sharp at every size.
 *
 * Traced from the owner's lotus artwork (brand/flower-source.png): a lit
 * core with eleven translucent petals. Each petal is a pointed vesica from
 * the core to its tip, filled with a light-to-blue gradient along its
 * length and edged with a fine ice-blue line. Back petals are drawn first,
 * the front row last, so the overlaps read as layers of glass.
 *
 *   node scripts/gen-lotus.mjs          writes brand/lotus.svg
 *   node scripts/gen-lotus.mjs --check  fails if it is stale (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const r = (n) => Math.round(n * 10) / 10;

// Measured on the artwork at 960x562: the core, then each petal's tip as
// an offset from it and its half-width at the widest point.
const CORE = [515, 400];
const PETALS = [
  // back row
  ["far-left", -482, -12, 80],
  ["upper-left", -396, -236, 92],
  ["top", -118, -380, 108],
  ["far-right", 406, -128, 74],
  ["upper-right", 256, -262, 92],
  // inner pair
  ["inner-left", -70, -170, 44],
  ["inner-right", 52, -190, 48],
  // front row
  ["mid-left", -236, -40, 58],
  ["mid-right", 214, -64, 58],
  ["low-left", -194, 140, 66],
  ["low-right", 298, 116, 74],
];

function petal([name, dx, dy, hw], i) {
  const [cx, cy] = CORE;
  const len = Math.hypot(dx, dy);
  const ux = dx / len, uy = dy / len, nx = -uy, ny = ux;
  const at = (a, b) => `${r(cx + ux * a + nx * b)} ${r(cy + uy * a + ny * b)}`;
  const d =
    `M${at(0, 0)}` +
    `C${at(len * 0.24, hw * 1.2)} ${at(len * 0.74, hw * 1.22)} ${at(len, 0)}` +
    `C${at(len * 0.74, -hw * 1.22)} ${at(len * 0.24, -hw * 1.2)} ${at(0, 0)}Z`;
  const tip = at(len, 0).split(" ");
  const grad = `g${i}`;
  return {
    def: `<linearGradient id="${grad}" gradientUnits="userSpaceOnUse" x1="${cx}" y1="${cy}" x2="${tip[0]}" y2="${tip[1]}">` +
      `<stop offset="0" stop-color="#FFF6EA" stop-opacity=".95"/>` +
      `<stop offset=".3" stop-color="#CFE0FF" stop-opacity=".5"/>` +
      `<stop offset=".75" stop-color="#6A9AE8" stop-opacity=".38"/>` +
      `<stop offset="1" stop-color="#3B6BC8" stop-opacity=".42"/></linearGradient>`,
    path: d,
    body: `<g data-petal="${name}"><path d="${d}" fill="url(#${grad})" stroke="url(#edge)" stroke-width="1.8" stroke-linejoin="round"/>` +
      `<path d="M${at(len * 0.08, 0)}L${at(len * 0.92, 0)}" stroke="#E6F0FF" stroke-opacity=".28" stroke-width=".9"/></g>`,
  };
}

const parts = PETALS.map(petal);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 960 562" role="img" aria-label="NOSHASHI">
<!-- NOSHASHI lotus. Generated by scripts/gen-lotus.mjs; edit there. -->
<defs>
<linearGradient id="edge" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#F2F7FF"/><stop offset="1" stop-color="#A9C8FF"/></linearGradient>
<radialGradient id="core" cx="${CORE[0]}" cy="${CORE[1]}" r="150" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#FFFFFF" stop-opacity=".95"/><stop offset=".25" stop-color="#FFF1DC" stop-opacity=".6"/><stop offset="1" stop-color="#9CC0FF" stop-opacity="0"/></radialGradient>
${parts.map((p) => p.def).join("\n")}
<clipPath id="petals">${parts.map((p) => `<path d="${p.path}"/>`).join("")}</clipPath>
<filter id="rim" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur stdDeviation="5"/></filter>
</defs>
<g filter="url(#rim)" opacity=".55">${parts.map((p) => `<path d="${p.path}" fill="none" stroke="#9CC2FF" stroke-width="5"/>`).join("")}</g>
${parts.map((p) => p.body).join("\n")}
<circle cx="${CORE[0]}" cy="${CORE[1]}" r="150" fill="url(#core)" clip-path="url(#petals)"/>
</svg>
`;

const outs = ["brand/lotus.svg"];
if (process.argv.includes("--check")) {
  const stale = outs.filter((f) => { try { return readFileSync(resolve(root, f), "utf8") !== svg; } catch { return true; } });
  if (stale.length) { console.error(`stale: ${stale.join(", ")} — run node scripts/gen-lotus.mjs`); process.exit(1); }
} else {
  for (const f of outs) { writeFileSync(resolve(root, f), svg); console.log(`wrote ${f}`); }
}
