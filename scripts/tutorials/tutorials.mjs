// The video tutorials on /tutorials/: screen recordings of the real site,
// driven by Playwright against the local preview (scripts/dev-site.mjs),
// which reads XRPL Mainnet live. scripts/tutorials/build.mjs records them.
//
// Nothing is staged. Every result on screen is read from a validated
// Mainnet ledger while the video is recorded, so the narration describes
// what each screen shows in general terms and never quotes a figure that
// could have changed by the time it was read. Example accounts are public
// issuers that published their own addresses.
//
// A tutorial is a list of steps:
//   ["go", path]            open a page
//   ["say", caption, spoken?]  caption on screen + narration (spoken text
//                           defaults to the caption, with SPOKEN applied)
//   ["type", selector, text]
//   ["click", selector]
//   ["wait", selector]      wait until it is visible (max 45 s)
//   ["waitText", selector, regex-source]  wait until its text matches
//   ["scroll", selector]    bring into view
//   ["wheel", px]           scroll gently by px
//   ["pause", ms]
//   ["live", name]          a step in build.mjs that reads the ledger itself

