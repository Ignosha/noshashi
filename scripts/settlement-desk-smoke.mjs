import { chromium } from 'playwright';
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
const require = createRequire(import.meta.url);
const output = process.env.SETTLEMENT_SMOKE_DIR || '/tmp/noshashi-settlement-smoke';
mkdirSync(output, { recursive: true });
const assert = require('node:assert/strict');
(async()=>{
  const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1050}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto((process.argv[2] || 'http://localhost:4337') + '/settlement-desk/');
  await page.screenshot({path:output + '/desktop.png',fullPage:true});
  await page.locator('[name=invoice_id]').fill('TEST FIXTURE · invoice A');
  await page.locator('[name=transaction_hash]').fill('A'.repeat(64));
  await page.locator('[name=destination]').fill('rHb9CJAWyB4rj91VRWn96DkukG4bwdtyTh');
  await page.locator('[name=expected_amount]').fill('10');
  let requests=0, unavailable=false;
  await page.route('**/api/settlement-check',async route=>{
    requests++; const input=route.request().postDataJSON();
    if (unavailable) return route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({status:'UNRESOLVED',error:'Ledger evidence unavailable'})});
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({status:'EXCEPTION', findings:['UNDERPAYMENT'], ledger_index:100, observed_at:'2026-11-12T00:00:00.000Z',source:'https://xrplcluster.com',delivered:{value:'9.000000',asset:{kind:'xrp'}},expectation:input.expectation,transaction_hash:input.transaction_hash,evidence:{fixture:true},receipt:{digest:'TEST FIXTURE ONLY'}})});
  });
  await page.getByRole('button',{name:'Compare with ledger'}).click();
  await page.getByText('underpayment',{exact:true}).waitFor();
  assert.equal(requests,1);
  await page.getByRole('button',{name:'Compare with ledger'}).click();
  await page.getByText('This exact check is already in your queue.').waitFor();
  assert.equal(requests,1);
  await page.getByRole('combobox',{name:'Human review (local session only)'}).selectOption('Investigating');
  await page.getByRole('textbox',{name:'Review note (no confidential information)'}).fill('TEST FIXTURE: confirm short delivery');
  await page.locator('[name=invoice_id]').click();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download evidence JSON'}).click();
  const download=await downloadPromise;
  await download.saveAs(output + '/test-fixture-receipt.json');
  const receipt=JSON.parse(require('node:fs').readFileSync(output + '/test-fixture-receipt.json','utf8'));
  assert.equal(receipt.review,'Investigating');assert.equal(receipt.notes,'TEST FIXTURE: confirm short delivery');assert.equal(receipt.review_history.length,3);
  await page.locator('[name=invoice_id]').fill('TEST FIXTURE · invoice B');
  await page.getByRole('button',{name:'Compare with ledger'}).click();
  await page.locator('.sd-case').nth(1).waitFor();
  assert.equal(await page.getByText('EXCEPTION · DUPLICATE PAYMENT REFERENCE',{exact:true}).count(),2);
  await page.getByRole('button',{name:'Matched',exact:true}).click();
  await page.getByText('No checks match this filter.').waitFor();
  await page.getByRole('button',{name:'All',exact:true}).click();
  await page.locator('#sd-kind').selectOption('issued');assert.equal(await page.locator('#sd-issued').isVisible(),true);
  await page.locator('#sd-kind').selectOption('xrp');assert.equal(await page.locator('#sd-issued').isVisible(),false);
  unavailable=true;
  await page.locator('[name=transaction_hash]').fill('B'.repeat(64));
  await page.getByRole('button',{name:'Compare with ledger'}).click();
  await page.getByText('Evidence is unresolved. No payment match established.').waitFor();
  assert.equal(await page.locator('.sd-case[data-status=UNRESOLVED]').count(),1);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(() => { const label = document.createElement('p'); label.textContent = 'BROWSER TEST — SYNTHETIC RESPONSE'; label.style.cssText = 'background:#fcde90;color:#111;padding:12px;position:sticky;top:0;z-index:1000'; document.body.prepend(label); });
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:output + '/mobile-test-fixture.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Browser checks passed: queue, duplicate guard, filters, issued fields, review export, mobile overflow, no JS errors. Mocked ledger response; not a live transaction.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
