import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const base = process.argv[2] || 'http://localhost:4347';
const out = process.env.SETTLEMENT_LIVE_DIR || '/tmp/noshashi-settlement-live';
const archive = JSON.parse(await readFile(new URL('../tests/fixtures/account-tx-solo-107587061.json', import.meta.url), 'utf8'));
const entry = archive.transactions.find(e => e.tx.TransactionType === 'Payment' && e.meta.delivered_amount?.value && !(e.tx.Flags & 0x20000));
const actual = entry.meta.delivered_amount;
const input = { transaction_hash: entry.tx.hash, expectation: { invoice_id: 'PUBLIC-ARCHIVE-VERIFICATION', destination: entry.tx.Destination, ...(entry.tx.DestinationTag === undefined ? {} : { destination_tag: entry.tx.DestinationTag }), asset: { kind: 'issued', currency: actual.currency, issuer: actual.issuer }, expected_amount: actual.value } };
const response = await fetch(`${base}/api/settlement-check`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(input), signal: AbortSignal.timeout(20000) });
const report = await response.json();
await mkdir(out, { recursive: true });
await writeFile(`${out}/live-report.json`, JSON.stringify({ http_status: response.status, report }, null, 2));
assert.equal(response.status, 200, `Live evidence unavailable: ${report.error}`);
assert.equal(report.status, 'MATCHED'); assert.equal(report.validated, true);
assert.equal(report.transaction_hash, entry.tx.hash);
assert.equal(report.ledger_index, entry.tx.ledger_index);
const { receipt, limitation, ...payload } = report;
assert.equal(receipt.digest, createHash('sha256').update(JSON.stringify(payload)).digest('hex'));
assert.ok(limitation.includes('not a digital signature'));
console.log(JSON.stringify({ http_status: response.status, status: report.status, transaction_hash: report.transaction_hash, ledger_index: report.ledger_index, source: report.source, observed_at: report.observed_at, receipt_verified: true, output: out }));
