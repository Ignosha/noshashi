"""
NOSHASHI logo variations, drawn from the site's own typefaces.

Writes standalone SVGs to site/brand/logos/ with every letter converted to
an outline, so the files render the same anywhere (no font needed):

  monogram.svg      the primary mark: a serif N on still water, rings spreading out
  monogram-lockup.svg  the monogram beside the wordmark
  split.svg         a drawn N whose diagonal is three ledgers with gaps
  mark.svg          the ledger mark: an N whose diagonal is three ledgers
  wordmark.svg      NOSHASHI in Instrument Serif over a hairline rule
  lockup.svg        mark + wordmark, horizontal
  seal.svg          a serif N inside a double ring, with the name set around it
  ripple.svg        a serif N with three ripple arcs leaving its diagonal
  tile.svg          the serif N on a dark tile, for avatars and app icons
  sheet.svg         all of the above on one sheet, dark and light

All original geometry: nothing is taken from the XRP or Ripple marks.
Run with a Python that has fontTools and brotli:
  python scripts/gen-logo-variations.py
"""
import math
import os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "site", "brand", "logos")
SERIF = TTFont(os.path.join(ROOT, "site", "fonts", "instrument-serif-400-latin.woff2"))
SANS = instantiateVariableFont(TTFont(os.path.join(ROOT, "site", "fonts", "inter-var-latin.woff2")), {"wght": 600})

INK, PAPER = "#EDEDED", "#0B0B0C"


def text_path(font, text, size, x, y, tracking=0.0):
    """Outline `text` at baseline (x, y); returns (path d, advance width)."""
    gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
    upm = font["head"].unitsPerEm
    k = size / upm
    pen = SVGPathPen(gs)
    cx = x
    for ch in text:
        name = cmap[ord(ch)]
        gs[name].draw(TransformPen(pen, (k, 0, 0, -k, cx, y)))
        cx += hmtx[name][0] * k + tracking * size
    return pen.getCommands(), cx - x - tracking * size


def text_on_circle(font, text, size, cx, cy, r, start_deg, tracking=0.0):
    """Outline `text` around a circle, reading clockwise from start_deg (0 = top)."""
    gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
    k = size / font["head"].unitsPerEm
    pen = SVGPathPen(gs)
    a = math.radians(start_deg)
    for ch in text:
        name = cmap[ord(ch)]
        w = hmtx[name][0] * k
        mid = a + (w / 2) / r
        # rotate glyph so its baseline is tangent to the circle
        rot = mid
        c, s = math.cos(rot), math.sin(rot)
        px, py = cx + r * math.sin(mid), cy - r * math.cos(mid)
        # glyph local origin at (-w/2, 0) relative to (px, py)
        t = (k * c, k * s, k * s, -k * c, px - (w / 2) * c, py - (w / 2) * s)
        gs[name].draw(TransformPen(pen, t))
        a += (w + tracking * size) / r
    return pen.getCommands()


def ledger_mark(x, y, s, color):
    """The ledger mark at (x, y), s px square."""
    u = s / 32
    return (f'<g transform="translate({x} {y}) scale({u})">'
            f'<path d="M8.5 23.5V8.5M23.5 8.5V23.5" stroke="{color}" stroke-width="2.6" stroke-linecap="round" fill="none"/>'
            f'<rect x="11" y="10" width="3.8" height="3.8" rx=".9" fill="{color}" opacity=".5"/>'
            f'<rect x="14.1" y="14.1" width="3.8" height="3.8" rx=".9" fill="{color}" opacity=".78"/>'
            f'<rect x="17.2" y="18.2" width="3.8" height="3.8" rx=".9" fill="{color}"/></g>')


def svg(w, h, body, bg=None):
    back = f'<rect width="{w}" height="{h}" fill="{bg}"/>' if bg else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}">'
            f'<!-- NOSHASHI. Generated by scripts/gen-logo-variations.py; edit there. -->{back}{body}</svg>\n')


def build(ink, paper):
    parts = {}
    # 1 mark
    parts["mark"] = (128, 128, ledger_mark(0, 0, 128, ink))
    # 2 wordmark
    d, w = text_path(SERIF, "NOSHASHI", 96, 0, 84, tracking=0.01)
    sub, sw = text_path(SANS, "XRPL INTELLIGENCE", 13, 0, 0, tracking=0.32)
    W = int(w) + 4
    sub, sw = text_path(SANS, "XRPL INTELLIGENCE", 13, (W - sw) / 2, 128, tracking=0.32)
    parts["wordmark"] = (W, 140, f'<path d="{d}" fill="{ink}"/><rect x="0" y="100" width="{W}" height="1" fill="{ink}" opacity=".5"/><path d="{sub}" fill="{ink}" opacity=".7"/>')
    # 3 lockup
    d, w = text_path(SERIF, "NOSHASHI", 64, 104, 66, tracking=0.01)
    parts["lockup"] = (int(104 + w + 4), 88, ledger_mark(-8, -6, 100, ink) + f'<path d="{d}" fill="{ink}"/>')
    # 4 seal
    S, c = 240, 120
    n, nw = text_path(SERIF, "N", 120, 0, 0)
    n, nw = text_path(SERIF, "N", 120, c - nw / 2, c + 42)
    label = "NOSHASHI · XRPL INTELLIGENCE · READ-ONLY LEDGER EVIDENCE · "
    _, raw = text_path(SANS, label, 12.5, 0, 0)
    fill = (2 * math.pi * 96 - raw) / (len(label) * 12.5)  # spread the letters round the whole ring
    ring = text_on_circle(SANS, label, 12.5, c, c, 96, 0, tracking=fill)
    parts["seal"] = (S, S, f'<circle cx="{c}" cy="{c}" r="116" fill="none" stroke="{ink}" stroke-width="2"/>'
                           f'<circle cx="{c}" cy="{c}" r="110" fill="none" stroke="{ink}" stroke-width=".8" opacity=".6"/>'
                           f'<circle cx="{c}" cy="{c}" r="80" fill="none" stroke="{ink}" stroke-width=".8" opacity=".6"/>'
                           f'<path d="{ring}" fill="{ink}" opacity=".85"/><path d="{n}" fill="{ink}"/>')
    # 5 ripple monogram
    n, nw = text_path(SERIF, "N", 150, 0, 0)
    n, nw = text_path(SERIF, "N", 150, 40, 150)
    arcs = "".join(f'<path d="M{150 + i * 22} {44 - i * 6} A{60 + i * 26} {60 + i * 26} 0 0 1 {150 + i * 22} {150 + i * 6}" fill="none" stroke="{ink}" stroke-width="{2.4 - i * .6}" opacity="{0.9 - i * .25}" stroke-linecap="round"/>' for i in range(3))
    parts["ripple"] = (240, 200, f'<path d="{n}" fill="{ink}"/>{arcs}')
    # 6 tile
    n, nw = text_path(SERIF, "N", 120, 0, 0)
    n, nw = text_path(SERIF, "N", 112, 64 - nw / 2, 98)
    tile_bg, tile_ink = ("#151517", "#EDEDED")
    parts["tile"] = (128, 128, f'<rect width="128" height="128" rx="28" fill="{tile_bg}"/>'
                               f'<rect x=".75" y=".75" width="126.5" height="126.5" rx="27.25" fill="none" stroke="#fff" stroke-opacity=".12" stroke-width="1.5"/>'
                               f'<path d="{n}" fill="{tile_ink}"/><rect x="44" y="108" width="40" height="2" rx="1" fill="{tile_ink}" opacity=".5"/>')
    # 7 monogram: the serif N on still water. Rings spread from the centre
    # and stop at the letter, which sits on a knockout in the ground colour.
    c = 120
    n, nw = text_path(SERIF, "N", 132, 0, 0)
    n, nw = text_path(SERIF, "N", 132, c - nw / 2, c + 46)
    rings = "".join(f'<circle cx="{c}" cy="{c}" r="{r}" fill="none" stroke="{ink}" stroke-width="{w}" opacity="{o}"/>'
                    for r, w, o in [(34, 1, .22), (50, 1, .3), (66, 1, .4), (82, 1.1, .52), (98, 1.3, .7)])
    parts["monogram"] = (240, 240, f'{rings}<circle cx="{c}" cy="{c}" r="114" fill="none" stroke="{ink}" stroke-width="2.4"/>'
                                   f'<path d="{n}" fill="{paper}" stroke="{paper}" stroke-width="10" stroke-linejoin="round"/>'
                                   f'<path d="{n}" fill="{ink}"/>')
    # 9 monogram lockup: the monogram beside the wordmark
    mono = parts["monogram"][2]
    d, w = text_path(SERIF, "NOSHASHI", 72, 132, 82, tracking=0.012)
    sub, sw = text_path(SANS, "XRPL INTELLIGENCE", 11.5, 134, 108, tracking=0.34)
    parts["monogram-lockup"] = (int(132 + w + 6), 120, f'<g transform="scale(.5)">{mono}</g><path d="{d}" fill="{ink}"/><path d="{sub}" fill="{ink}" opacity=".6"/>')
    # 8 split: a drawn N whose diagonal is three ledgers with gaps between them
    segs = ""
    for i in range(3):
        t0, t1 = i / 3 + .035, (i + 1) / 3 - .035
        x0, y0 = 70 + 100 * t0, 62 + 116 * t0
        x1, y1 = 70 + 100 * t1, 62 + 116 * t1
        segs += f'<line x1="{x0:.1f}" y1="{y0:.1f}" x2="{x1:.1f}" y2="{y1:.1f}" stroke="{ink}" stroke-width="17" opacity="{(.45, .72, 1)[i]}"/>'
    parts["split"] = (240, 240, f'<rect x="8" y="8" width="224" height="224" rx="52" fill="none" stroke="{ink}" stroke-width="2.4"/>'
                                f'<line x1="70" y1="58" x2="70" y2="182" stroke="{ink}" stroke-width="12" stroke-linecap="round"/>'
                                f'<line x1="170" y1="58" x2="170" y2="182" stroke="{ink}" stroke-width="12" stroke-linecap="round"/>{segs}')
    return parts


def main():
    os.makedirs(OUT, exist_ok=True)
    dark = build(INK, PAPER)
    light = build("#111112", "#F4F4F2")
    for name, (w, h, body) in dark.items():
        open(os.path.join(OUT, f"{name}.svg"), "w").write(svg(w, h, body))
    for name, (w, h, body) in light.items():
        if name != "tile":
            open(os.path.join(OUT, f"{name}-ink.svg"), "w").write(svg(w, h, body))
    # contact sheet: two rows, dark and light
    order = ["monogram", "monogram-lockup", "split", "wordmark", "seal", "tile"]
    cell, pad = 300, 40
    W, H = cell * 3, cell * 4
    out = []
    for row, (parts, bg, fg) in enumerate([(dark, PAPER, INK), (light, "#F4F4F2", "#111112")]):
        out.append(f'<rect y="{row * cell * 2}" width="{W}" height="{cell * 2}" fill="{bg}"/>')
        for i, name in enumerate(order):
            w, h, body = parts[name]
            sc = min((cell - 2 * pad) / w, (cell - 2 * pad - 30) / h)
            x = (i % 3) * cell + (cell - w * sc) / 2
            y = row * cell * 2 + (i // 3) * cell + (cell - 30 - h * sc) / 2
            out.append(f'<g transform="translate({x:.1f} {y:.1f}) scale({sc:.4f})">{body}</g>')
            lab, lw = text_path(SANS, f"{i + 1}  {name.upper()}", 11, 0, 0, tracking=0.2)
            lab, lw = text_path(SANS, f"{i + 1}  {name.upper()}", 11, (i % 3) * cell + (cell - lw) / 2, row * cell * 2 + (i // 3) * cell + cell - 22, tracking=0.2)
            out.append(f'<path d="{lab}" fill="{fg}" opacity=".55"/>')
    open(os.path.join(OUT, "sheet.svg"), "w").write(svg(W, H, "".join(out)))
    print("wrote", sorted(os.listdir(OUT)))


if __name__ == "__main__":
    main()
