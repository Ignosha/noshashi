"""Academy wordmark and transparent circular icon, using the site's outlined type.

Run with the same fontTools/brotli environment as gen-logo-variations.py.
The typography is paths, so desktop installers need no additional fonts.
"""
from pathlib import Path
import runpy

ROOT = Path(__file__).resolve().parent.parent
brand = runpy.run_path(str(ROOT / "scripts/gen-logo-variations.py"))
text_path, serif = brand["text_path"], brand["SERIF"]


def line(text, size, width, baseline):
    _, advance = text_path(serif, text, size, 0, 0)
    path, _ = text_path(serif, text, size, (width - advance) / 2, baseline)
    return f'<path d="{path}" fill="#EDEDED"/>'


def svg(viewbox, body, label):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" role="img" aria-label="{label}">'
            '<!-- Generated by scripts/gen-academy-brand.py. Outlined Instrument Serif. -->'
            f'{body}</svg>\n')


out = ROOT / "public/brand"
out.mkdir(parents=True, exist_ok=True)
icon = ('<circle cx="120" cy="120" r="116" fill="#0B0B0C" stroke="#EDEDED" stroke-width="1.4"/>'
        '<circle cx="120" cy="120" r="108" fill="none" stroke="#EDEDED" stroke-opacity=".4" stroke-width=".6"/>'
        + line("Noshashi", 44, 240, 110)
        + '<path d="M58 125H182" stroke="#EDEDED" stroke-opacity=".5" stroke-width=".7"/>'
        + line("Academy", 44, 240, 162))
(out / "academy-icon.svg").write_text(svg("-8 -8 256 256", icon, "Noshashi Academy"))

first, width = text_path(serif, "Noshashi", 44, 0, 42)
second, _ = text_path(serif, "Academy", 44, width + 15, 42)
(out / "academy-wordmark.svg").write_text(svg(f"0 0 {width * 2 + 40:.2f} 53", f'<path d="{first}{second}" fill="#EDEDED"/>', "Noshashi Academy"))
print("wrote Academy icon and wordmark")
