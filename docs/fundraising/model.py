"""Seed model for NOSHASHI: a $4.5M round over 24 months.

Every input is an ASSUMPTION written here so it can be changed and the
tables regenerated: `python3 docs/fundraising/model.py > docs/fundraising/model.md`.
Nothing in it is a booking, a quote or a commitment. Actual revenue to
date is $0 (production database, 2026-10-26).
"""

ROUND = 4_500_000
MONTHS = 24

# (role, monthly fully loaded cost in USD, first month) - estimates for
# remote hires; replace with real offers.
HIRES = [
    ("Founder (salary)", 12_000, 1),
    ("Engineer: Rust / XRPL", 20_000, 2),
    ("Sales and solutions lead", 18_000, 4),
    ("Engineer: platform and API", 18_000, 6),
    ("Security and compliance engineer", 19_000, 9),
    ("Customer engineer", 15_000, 12),
    ("Engineer: integrations", 18_000, 15),
]

def other(m):
    """Non-people spend in month m, by line. Estimates, to be replaced by quotes."""
    lines = {
        # $45/month paid tiers now (docs/FUNDING_NEEDS.md); own full-history
        # node and point-in-time recovery from month 4; SLA and dedicated
        # environments from month 12.
        "Infrastructure": 45 if m < 4 else 1_500 if m < 12 else 4_000,
        "Software and tools": 1_500,
        "Legal and accounting": 25_000 if m <= 2 else 4_000,
        "Insurance (cyber, E&O)": 0 if m < 6 else 2_500,
        "Penetration test": 30_000 if m == 8 else 0,
        "SOC 2 Type I (auditor + tooling)": 20_000 if 10 <= m <= 12 else 0,
        "SOC 2 Type II (auditor + tooling)": 12_000 if 18 <= m <= 24 else 0,
        "Travel and XRPL events": 3_000,
        "Code signing (Apple, Windows)": 99 + 10 if m in (1, 13) else 10,
    }
    return lines

CONTINGENCY = 0.10

# Monthly recurring revenue at months 6, 12, 18 and 24 per scenario;
# linear in between. Pilots are one-off revenue, counted separately.
SCENARIOS = {
    "Downside": {"mrr": {6: 0, 12: 5_000, 18: 12_000, 24: 25_000}, "pilots": {4: 0, 8: 1, 12: 2, 24: 6}, "pilot_fee": 5_000},
    "Base": {"mrr": {6: 3_000, 12: 25_000, 18: 70_000, 24: 150_000}, "pilots": {4: 1, 8: 3, 12: 6, 24: 14}, "pilot_fee": 7_500},
    "Upside": {"mrr": {6: 8_000, 12: 60_000, 18: 220_000, 24: 500_000}, "pilots": {4: 2, 8: 5, 12: 10, 24: 24}, "pilot_fee": 10_000},
}

def interp(points, m):
    keys = sorted(points)
    if m <= keys[0]:
        return points[keys[0]] * m / keys[0] if keys[0] else points[keys[0]]
    for a, b in zip(keys, keys[1:]):
        if a <= m <= b:
            return points[a] + (points[b] - points[a]) * (m - a) / (b - a)
    return points[keys[-1]]

def people(m):
    return sum(cost for _, cost, start in HIRES if m >= start)

def spend(m):
    return (people(m) + sum(other(m).values())) * (1 + CONTINGENCY)

def run(s):
    cash, rows, prev_pilots = ROUND, [], 0
    for m in range(1, MONTHS + 1):
        mrr = interp(s["mrr"], m)
        pilots_total = round(interp(s["pilots"], m))
        pilot_rev = (pilots_total - prev_pilots) * s["pilot_fee"]
        prev_pilots = pilots_total
        revenue = mrr + pilot_rev
        cost = spend(m)
        cash += revenue - cost
        rows.append((m, mrr, pilot_rev, cost, cash))
    return rows

def money(x):
    return f"${x:,.0f}" if x >= 0 else f"-${-x:,.0f}"

def main():
    print("<!-- Generated by docs/fundraising/model.py. Edit the script, not this file. -->\n")
    print("## Spending plan (assumptions)\n")
    print("| Role | Monthly, fully loaded | From month | 24-month cost |")
    print("|---|---|---|---|")
    total_people = 0
    for role, cost, start in HIRES:
        c = cost * (MONTHS - start + 1)
        total_people += c
        print(f"| {role} | {money(cost)} | {start} | {money(c)} |")
    print(f"| **People** | | | **{money(total_people)}** |\n")
    other_totals = {}
    for m in range(1, MONTHS + 1):
        for k, v in other(m).items():
            other_totals[k] = other_totals.get(k, 0) + v
    print("| Other line | 24-month cost |")
    print("|---|---|")
    for k, v in other_totals.items():
        print(f"| {k} | {money(v)} |")
    base_total = total_people + sum(other_totals.values())
    print(f"| Contingency ({CONTINGENCY:.0%}) | {money(base_total * CONTINGENCY)} |")
    total = base_total * (1 + CONTINGENCY)
    print(f"| **Total 24-month spend** | **{money(total)}** |\n")
    print(f"Against a {money(ROUND)} round that leaves {money(ROUND - total)} unspent with zero revenue. "
          f"Monthly spend runs from {money(spend(1))} in month 1 to {money(spend(MONTHS))} in month 24. "
          f"Headcount reaches {len(HIRES)} including the founder. "
          f"With no revenue at all and month-24 spend held flat afterwards, the round lasts about "
          f"{MONTHS + (ROUND - total) / spend(MONTHS):.0f} months.\n")
    print("## Scenarios\n")
    print("| Scenario | MRR month 12 | MRR month 24 | ARR month 24 | Pilots sold (24 mo) | Revenue (24 mo) | Cash at month 24 | Lowest cash |")
    print("|---|---|---|---|---|---|---|---|")
    for name, s in SCENARIOS.items():
        rows = run(s)
        rev = sum(r[1] + r[2] for r in rows)
        low = min(r[4] for r in rows)
        print(f"| {name} | {money(interp(s['mrr'], 12))} | {money(s['mrr'][24])} | {money(s['mrr'][24] * 12)} | "
              f"{s['pilots'][24]} at {money(s['pilot_fee'])} | {money(rev)} | {money(rows[-1][4])} | {money(low)} |")
    print()
    for name, s in SCENARIOS.items():
        rows = run(s)
        print(f"<details><summary>{name}: month by month</summary>\n")
        print("| Month | MRR | Pilot revenue | Spend | Cash |")
        print("|---|---|---|---|---|")
        for m, mrr, pr, cost, cash in rows:
            print(f"| {m} | {money(mrr)} | {money(pr)} | {money(cost)} | {money(cash)} |")
        print("\n</details>\n")

if __name__ == "__main__":
    main()
